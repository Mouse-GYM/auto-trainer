from dataclasses import dataclass
from typing import Protocol, Callable

from autotrainer.behavior.analysis.intersession_process import IntersessionResponse
from autotrainer.inference import PoseAlgorithm


@dataclass
class SegmentationConfiguration:
    nonce: str
    session_index: int
    complete: Callable[[str, bool], None]


@dataclass
class DetectionConfiguration:
    nonce: str
    complete: Callable[[str, bool], None]


class InferenceProtocol(Protocol):
    @property
    def pose_algorithm(self) -> PoseAlgorithm: ...

    def perform_segmentation(self, configuration: SegmentationConfiguration): ...

    def perform_detection(self, configuration: DetectionConfiguration): ...

    def perform_live(self): ...

    # "dynamic" event handler attribute,
    # we must not define it as a real method in the protocol, otherwise it's taking over the dynamic one
    # being generated by Events
    detection_result_ready: Callable[[IntersessionResponse], None]
