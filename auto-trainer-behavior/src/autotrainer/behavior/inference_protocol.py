from typing import Protocol, Callable, Tuple, Optional

from autotrainer.core import Offset3DTuple, ObservableObject

from autotrainer.core.configuration.inference_configuration import InferenceConfiguration

import autotrainer.inference.analysis

from autotrainer.inference import InferenceStatus, PoseAlgorithm
from . import SegmentationConfiguration, DetectionConfiguration


class _InferenceProtocol(Protocol):

    status: InferenceStatus

    def stop(self):
        """Stop inference ; it can still be restarted after"""

    def terminate(self):
        """Terminate totally"""

    def load_configuration(self, config: InferenceConfiguration):
        """Load the given configuration"""

    def save_configuration(self) -> InferenceConfiguration:
        """Returns current configuration"""

    @property
    def pose_algorithm(self) -> PoseAlgorithm:
        """Current associated pose_algo"""

    @property
    def is_enabled(self) -> bool:
        """Wether enabled or not"""
        return False

    def perform_segmentation(self, configuration: SegmentationConfiguration) -> Optional[SegmentationConfiguration]:
        """Perform segmentation with given segment config, returns the passed config if succeeded, else None"""

    def perform_detection(self, configuration: DetectionConfiguration) -> Optional[DetectionConfiguration]:
        """Perform detection with given segment config, returns the passed config if succeeded, else None"""

    def perform_live(self):  # unused
        """Perform live"""

    def set_inference_to_online(self):
        """Request inference to switch to online mode"""

    # "dynamic" event handler attributes,
    # we must not define as real methods in the protocol,
    # otherwise that's taking over the dynamic one being generated by Events, which break these events handling.
    # only defining as type hints,
    # to be more friendly/correct with IDEs and dynamic attributes accesses.
    detection_result_ready: Callable[[autotrainer.inference.analysis.IntersessionResponse], None]
    pose_response_ready: Callable[[autotrainer.inference.PoseResponse], None]
    algo_initialised: Callable[[autotrainer.inference.PoseAlgorithm], None]
    diamond_triangle_offset_changed: Callable[[Optional[Offset3DTuple]], None]
    star_triangle_offset_changed: Callable[[Optional[Offset3DTuple]], None]
    triangle_pellet_offset_changed: Callable[[Optional[Offset3DTuple]], None]


class InferenceProtocol(ObservableObject, _InferenceProtocol):

    STATUS = "status"

    def __init__(self):
        super().__init__(event_names=(
            'pose_response_ready',
            'detection_result_ready',
            'diamond_triangle_offset_changed',
            'star_triangle_offset_changed',
            'triangle_pellet_offset_changed',
            'algo_initialised',
        ))
